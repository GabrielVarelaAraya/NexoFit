// Stub para la vista previa web (ver metro.config.js): reemplaza a los
// componentes nativos generados por codegen de react-native-screens, que solo
// existen para iOS/Android. Los eventos nativos (onWillAppear, etc.) se
// ignoran en web. No se usa en builds nativos.
import React from 'react';
import { View } from 'react-native';

const GeneratedNativeComponent = React.forwardRef(function GeneratedNativeComponent(props, ref) {
  return React.createElement(View, { ref, style: props.style }, props.children);
});

export default GeneratedNativeComponent;
